/**
 * Reads firebase-service-account.json and writes .env.local with VITE_FIREBASE_* web config.
 * Run from repo root: node scripts/setup-firebase-env.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { GoogleAuth } = require('../functions/node_modules/google-auth-library');

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const saPath = path.join(root, 'firebase-service-account.json');
const envPath = path.join(root, '.env.local');

if (!fs.existsSync(saPath)) {
  console.error('Missing firebase-service-account.json in project root.');
  process.exit(1);
}

const sa = JSON.parse(fs.readFileSync(saPath, 'utf8'));
const projectId = sa.project_id;

const auth = new GoogleAuth({
  credentials: sa,
  scopes: ['https://www.googleapis.com/auth/firebase.readonly'],
});
const client = await auth.getClient();
const { token } = await client.getAccessToken();
const headers = { Authorization: `Bearer ${token}` };

const listRes = await fetch(
  `https://firebase.googleapis.com/v1beta1/projects/${projectId}/webApps`,
  { headers },
);
const listJson = await listRes.json();
if (!listRes.ok) {
  console.error('Failed to list web apps:', listJson);
  process.exit(1);
}

const apps = listJson.apps || [];
if (!apps.length) {
  console.error('No Firebase web apps found. Create one in Firebase Console first.');
  process.exit(1);
}

const configRes = await fetch(
  `https://firebase.googleapis.com/v1beta1/${apps[0].name}/config`,
  { headers },
);
const config = await configRes.json();
if (!configRes.ok) {
  console.error('Failed to fetch web app config:', config);
  process.exit(1);
}

const lines = [
  '# Generated by scripts/setup-firebase-env.mjs',
  `VITE_FIREBASE_API_KEY=${config.apiKey || ''}`,
  `VITE_FIREBASE_AUTH_DOMAIN=${config.authDomain || `${projectId}.firebaseapp.com`}`,
  `VITE_FIREBASE_PROJECT_ID=${config.projectId || projectId}`,
  `VITE_FIREBASE_STORAGE_BUCKET=${config.storageBucket || `${projectId}.firebasestorage.app`}`,
  `VITE_FIREBASE_MESSAGING_SENDER_ID=${config.messagingSenderId || ''}`,
  `VITE_FIREBASE_APP_ID=${config.appId || ''}`,
];

if (config.measurementId) {
  lines.push(`VITE_FIREBASE_MEASUREMENT_ID=${config.measurementId}`);
}

const existing = fs.existsSync(envPath) ? fs.readFileSync(envPath, 'utf8') : '';
const vapidMatch = existing.match(/^VITE_FIREBASE_VAPID_KEY=(.*)$/m);
lines.push(`VITE_FIREBASE_VAPID_KEY=${vapidMatch?.[1]?.trim() || ''}`);
lines.push('');
lines.push('# Server-side Firebase Admin (not exposed to browser)');
lines.push('GOOGLE_APPLICATION_CREDENTIALS=./firebase-service-account.json');

if (!vapidMatch?.[1]?.trim()) {
  lines.push('');
  lines.push('# Add VITE_FIREBASE_VAPID_KEY from Firebase Console → Cloud Messaging → Web Push certificates');
}

fs.writeFileSync(envPath, `${lines.join('\n')}\n`, 'utf8');
console.log(`Wrote ${envPath}`);
if (!vapidMatch?.[1]?.trim()) {
  console.log('Note: VITE_FIREBASE_VAPID_KEY still needs to be set manually in .env.local.');
}
